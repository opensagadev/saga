// Particles_Load @0x4a2a50.
void Particles_Load(WORLDINFO *world, char **debris_name, i32 count, i32 flags) {
    char path[0x100];

    world->page_pp = -1;
    sprintf(path, "%s.ptl", world->config_file);
    if (NuFileExists(path) != 0) {
        world->page_pp = edppLoadPage(path, 1, reinterpret_cast<usize>(world->current_gscn));
    }

    world->debris_sys = (APIDEBRISSYS_s *)InitGameDebris(&world->giz_buffer, &world->unknown_0108, count, flags,
                                                         debris_name, (char)world->page_pp);
}

void Particles_LoadAreaPage(char *path) {
    DEBPAGE_AREA = -1;
    if (NuFileExists(path) != 0) {
        DEBPAGE_AREA = edppLoadPage(path, 1, 0);
    }
}

void Particles_DumpAreaPage() {
    if (DEBPAGE_AREA != -1) {
        edppStopPage(static_cast<i8>(DEBPAGE_AREA));
        edppClearPage(static_cast<i8>(DEBPAGE_AREA));
        DEBPAGE_AREA = -1;
    }
}

void Particles_Start(WORLDINFO_s *world) {
    if (DEBPAGE_AREA != -1) {
        edppStartPage((i8)DEBPAGE_AREA);
    }
    if (world->page_pp != -1) {
        edppStartPage((i8)world->page_pp);
    }
    DebrisSetRenderGroup(1);
    if (world->page_anim >= 0) {
        edanimStartPage(world->page_anim);
    }
}

void Particles_Stop(WORLDINFO_s *world) {
    if (world->page_anim != -1) {
        edanimStopPage(world->page_anim);
    }
    if (world->page_pp != -1) {
        edppStopPage((i8)world->page_pp);
    }
    if (DEBPAGE_CHARACTER != -1) {
        edppStopPage((i8)DEBPAGE_CHARACTER);
    }
    if (DEBPAGE_GENERAL != -1) {
        edppStopPage((i8)DEBPAGE_GENERAL);
    }
    if (DEBPAGE_AREA != -1) {
        edppStopPage((i8)DEBPAGE_AREA);
    }
    DebFreeAllCreatedEffects();
}

void SetEffectVisibility(char *name, i32 visible) {
    i32 type = LookupDebrisEffectPageOnly(name, static_cast<char>(WorldInfo_CurrentlyActive()->page_pp));
    if (type != -1) {
        if (visible != 0)
            DebrisTypeStatusAlwaysOn(type);
        else
            DebrisTypeStatusAlwaysOff(type);
    }
}

