static u32 NuQFntModeStack[16];
static i32 NuQFntModeStackIndex;

void NuQFntPushPrintMode(u32 mode) {
    if (NuQFntModeStackIndex < 16)
        NuQFntModeStack[NuQFntModeStackIndex++] = NuQFntMode;
    NuQFntMode = mode;
}

